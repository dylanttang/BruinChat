const assert = require('node:assert/strict');
const fs = require('node:fs');
const { createRequire } = require('node:module');
const metroRequire = createRequire(require.resolve('metro/package.json'));
const image = metroRequire('image-size');
const imageFn = image.__esModule ? image.default : image;
const size = imageFn(fs.readFileSync(require.resolve('../src/assets/icon.png')));
assert.ok(size.width > 0 && size.height > 0);
const xcode = require('xcode');
const project = new xcode.project('/tmp/test.pbxproj');
project.hash = { project: { objects: {} } };
assert.match(project.generateUuid(), /^[A-F0-9]{24}$/);
const expoRequire = createRequire(require.resolve('expo/package.json'));
const postcss = createRequire(expoRequire.resolve('@expo/metro-config/package.json'))('postcss');
assert.equal(postcss.parse('a { color: red }').first.selector, 'a');
const queryString = require('query-string');
assert.equal(queryString.parse('q=hello%20world').q, 'hello world');
assert.equal(queryString.stringify({ q: 'a&b' }), 'q=a%26b');
assert.equal(typeof queryString.parse('q=%E0%A4%A').q, 'string');
console.log('Patched Metro image decoding, Xcode UUIDs, PostCSS and URL parsing passed');
